/// 「未送信のログをまとめて送る」の対象にする練習時間の下限 [秒]。
///
/// 前提: 開発者が集めたいのは実際の練習のログで、桟橋での試し起動や
/// 数分の移動は解析の役に立たない。15分あれば、桜川の1往復の一部と
/// 複数の警告場面が入る(2026-10-28 利用者決定)。
/// 練習時間はアプリ内の定義(艇が動いていた時間 = `movingTimeSec`)で数える。
const double bulkLogExportMinPracticeSec = 15 * 60;

/// 「未送信のログをまとめて送る」の対象にする監視ログの長さの下限 [秒]。
///
/// 前提: 監視端末は動かないので、距離は使えない。代わりに「その間に1艇以上が
/// 航行していた」ことを条件にする(2026-10-29 利用者決定)。艇が1艇も航行しない
/// 監視は、解析に役立つ航跡が入っていない。10分あれば1往復の一部は入る。
const double bulkPracticeLogMinDurationSec = 10 * 60;

/// 同じく距離の下限 [m]。15分と同じ理由で、短い移動を除く(2026-10-28 利用者決定)。
const double bulkLogExportMinDistanceMeters = 2000;

/// まとめて送るZIP 1つの大きさの上限 [byte]。
///
/// 前提: 1練習の診断ZIPは実測 0.1〜0.55MB(2026-08-06・09 の実機ログ)。
/// LINE の上限(1GBとされる)よりずっと小さく保ち、通信の弱い桟橋でも
/// 送り切れる大きさにする。超えるときは複数のZIPに分けて一度に渡す。
const int bulkLogExportMaxZipBytes = 25 * 1024 * 1024;

/// 警告エピソードを種類ごとに最初に見せる件数。
///
/// 前提: 1練習の警告エピソードは実測 41〜794件(2026-08-06)。全件を並べると
/// どれがいつの何か分からず、下の共有ボタンにも届かない。気になった場面を
/// 選んで評価できれば足りるので、危険度の高いものから少しだけ出す。
const int alertEpisodePreviewPerCategory = 5;
