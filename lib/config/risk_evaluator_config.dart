// =====================================================
// 衝突リスク評価の設定値
// 桜川(土浦市)での運用に合わせて調整する場合はここを編集する
// =====================================================

/// 連続音の本警告へ上げる到達予測の残り時間 [秒]。
///
/// 8+ の停止時間は速度によらず約8.15秒なので、そこへ余裕を加えた
/// 10秒を既定にする。これは予測地平ではなく、提示の切替点である。
const primaryWarningLeadSeconds = 10.0;

/// 断続音の予告を始める到達予測の残り時間 [秒]。
///
/// 予測地平と同じ値に保つ。不変条件「予測が届かない先では音を鳴らさない」
/// を、この値を経由して守る。カーブ間隔200m・巡航5m/sの運用前提に対し、
/// 13秒(65m)までを川なりに予測する。
const advanceWarningLeadSeconds = 13.0;

/// 後方互換のため残す、予測地平を表す旧名。
/// 新しいコードは [advanceWarningLeadSeconds] を使うこと。
const defaultWarningTimeSeconds = advanceWarningLeadSeconds;

/// 推測警告の設定可能範囲 [秒]。
///
/// 下限 9.0 の根拠: **予測地平が最長の停止時間(8+ の 8.15秒)を下回ると、
/// 停止距離内にある脅威すら検知できなくなる。** 停止距離内に入っている
/// 時点で「漕ぎ止めても止まりきれない」のだから、そこを見ない設定を
/// 選べてしまってはいけない。8.15秒に僅かな余裕を足して 9.0 とする。
/// (停止時間は 1x 6.95 / 2x 6.60 / 4x 6.68 / 8+ 8.15秒。式が速度に線形
///  なので速度によらず一定。`boat_config.dart`)
const minWarningTimeSeconds = 9.0;
const maxWarningTimeSeconds = 25.0;
const warningTimeStepSeconds = 1.0;

/// 本警告の下限 [秒]。8+ の停止時間8.15秒より大きくする。
const minPrimaryWarningLeadSeconds = 8.5;

/// 本警告の設定刻み [秒]。
const primaryWarningLeadStepSeconds = 0.5;

/// コード上の予測地平のデフォルト値。実運用では保存された設定値を使用する。
const warningTime = advanceWarningLeadSeconds;

// =====================================================
// 静的危険区域への近接補助距離 [m](kind別)
// -----------------------------------------------------
// 航路中心線に沿った予測(下記)が入ったことで、「岸へ向かっている」ケースは
// 掃引が正しく検知するようになった。近接判定に残る仕事は次の3つだけ。
//   1. 停止中の風・流れによる漂流
//   2. 低速で進行方向が定まらないとき
//   3. 幾何判定が例外を投げたときの予備
// したがって一律15mは過大。桜川(川幅50m、狭い区間35m)では、
// 岸の危険区域(水面側5m)の縁まで通常4〜8mで走るため、岸を大きく取ると
// 常時鳴って形骸化する。帰結の大きさで kind ごとに分ける。
//
// 警告そのものを止めたい区域は、この値を0にするのではなく
// `FixedObstacleWarningSettings`(isWarningEnabled)で外すこと。
// 0を「機能OFF」の合図に流用すると、データ調整と機能停止が区別できなくなる。
// =====================================================

/// 岸。常に近くを走るため最小。「本当に触れる寸前」だけ知らせる。
const shoreProximityCautionDistanceMeters = 3.0;

/// 橋。橋脚に当たる帰結が大きい。
const bridgeProximityCautionDistanceMeters = 6.0;

/// 橋脚は水中に立つ実体で、正面衝突の帰結が大きい。一方で局所的なので、
/// 流木と同じ6mなら岸のような常時警告にはならない(DESIGN_PRINCIPLES 1.3)。
const bridgePierProximityCautionDistanceMeters = 6.0;

/// 中州。
const islandProximityCautionDistanceMeters = 5.0;

/// 流木。水面下で見えず、帰結が最悪。
const driftwoodProximityCautionDistanceMeters = 6.0;

/// テスト区域。
const testZoneProximityCautionDistanceMeters = 5.0;

/// 種別未指定(アプリ内で描いた臨時危険区域を含む)。
/// 現地で見つけた流木などが主なので、流木相当にする。
const genericProximityCautionDistanceMeters = 6.0;

/// カーブ・逆走の案内区域は近接判定の対象外(区域進入イベントとして扱う)。
const guidanceProximityCautionDistanceMeters = 0.0;

/// 近接補助距離として許容する上限 [m]。
/// 空間索引へ渡す問い合わせ半径の上界にも使う。個別の上書き値も
/// この値を超えないこと。
const maxProximityCautionDistanceMeters = 15.0;

// =====================================================
// 静的危険区域の掃引クリアランス [m](kind別)
// -----------------------------------------------------
// 連続掃引に使う領域の「横方向(w)」だけを kind ごとに決める。
// 前後方向(h)と s は排他領域のまま変えないので、区域へ向かって進んでいる
// 艇の検知時刻は一切変わらない。減らすのは「並走で横に触れる」偽陽性だけ。
// =====================================================

/// 静的危険区域の掃引に使う片側クリアランス [m](船体領域の横幅からの追加分)。
///
/// 既定 1.5m は排他領域の横幅と全艇種で一致する
/// (1x/2x/4x: 6.0+3.0=9.0、8+: 7.5+3.0=10.5)。
/// 排他領域は「他船に空けてほしい水面」を表す船舶領域の概念であり、
/// **並走することが正常な岸**へそのまま当てると
/// DESIGN_PRINCIPLES 1.4「岸から数mを走るのは正常」と衝突する。
const defaultStaticSweepClearanceMeters = 1.5;

/// 岸。船体+オールが危険区域へ入るまで鳴らさない。
/// 岸区域は基準線から水面側5mなので、実質「オールの先が岸から5m以内」で鳴る。
/// 1.2 狭所の片側レーン12.5m(艇中心は岸から11.25m)に対し2m以上の余裕が残る。
const shoreStaticSweepClearanceMeters = 0.0;

/// 近接注意を「接近中」と認める最小の接近速度 [m/s]。
///
/// 以前は2秒で0.25m(=0.125m/s)でも接近扱いにしていたため、通常の操舵の
/// ふらつきで岸沿いに点滅していた。実際に寄っていく速度を要求する。
const proximityApproachRateMetersPerSecond = 0.4;

/// 接近判定に使う先読み時間 [秒]。
const proximityApproachLookaheadSeconds = 2.0;

/// これ未満は進行方向が不安定なため、接近速度を解除根拠にしない。
const proximityDirectionUnknownSpeedMetersPerSecond = 0.5;

/// 他艇情報の可視TTL [秒]。超過後は幽霊艇として削除する。
/// 停止中の10秒送信に通信ジッタが重なっても表示落ちしないよう、
/// 送信間隔の3倍を確保する。予測入力は別の6秒で打ち切る。
const boatStaleTimeoutSeconds = 30;

/// 不正な他艇レコードを診断上保持する時間 [秒]。
///
/// これは通信経路の障害ではない。最後に受理された艇の位置が可視TTLを
/// 過ぎるまで、同じ艇の連続した不正更新を追跡できるようにするためだけの
/// 診断保持時間である。可視TTLと同じにし、古い艇IDを残し続けない。
const remoteDataRejectionRetentionSeconds = boatStaleTimeoutSeconds;

/// 直線外挿と新規衝突判定に使える最大鮮度 [秒]。
/// 6秒以上途絶した他艇は予測を作らず、既存警告はFSM側で保持する。
const boatPredictionTimeoutSeconds = 6;

// =====================================================
// 位置不確実性(GPS誤差・データの古さ)のマージン設定
// -----------------------------------------------------
// 水上のスマホGPSは5〜15m程度の誤差が普通に発生する。
// 排他領域と船体領域の差(全艇種で1.5m)だけでは、GPS誤差で
// 実際には接触寸前の2艇が「離れている」ように見えて警告が漏れる。
// そこで衝突判定時に、GPS推定誤差(accuracy)とデータの経過時間を
// 用途別に制限したマージンとして反映する。
//
// マージン込みでのみ重なる場合は「不確実な脅威」として、確実な
// 重なりより1段低いレベルで警告する(緊急lv3は確実な重なりのみ)。
//
// 桜川での過剰警告チェック(狭い区間・実効航路幅25m):
//   静的: 25m − 2×1.5m = 22m。艇の半幅5.25m(8+)で中心から5.5mの余裕。
//
//   他艇: 「重ならないための中心間距離」= 排他半幅 + 相手の船体半幅 + guard。
//         guard は accuracy 由来(上限2.5m)+ 外挿由来(上限2.4m)= 最悪4.9m。
//         通常(accuracy 5m 同士・齢2秒)は 1.41 + 0.8 = 2.2m。
//
//   | 艇種の組 | 基本(guard 0) | +通常2.2m | +最悪4.9m |
//   | --- | --- | --- | --- |
//   | 1x/2x/4x 同士 | 4.5+3.0 = 7.50m | 9.70m | **12.40m** |
//   | 8+ 同士       | 5.25+3.75 = 9.00m | 11.20m | **13.90m** |
//
//   キープライト時の艇間は通常20m、狭い区間で12.5m(DESIGN_PRINCIPLES 1.2)。
//   1x/2x/4x: 12.40 < 12.5 → 成立(ただし余裕0.1m)。
//   **8+ 同士: 13.90 > 12.5 → 1.4m 超過する。**
//
//   すなわち狭所で 8+ 同士がすれ違い、かつ双方のGPS精度が悪い(または
//   データ齢が5〜6秒)ときは、`guarded` 側が重なって不確実脅威になり、
//   3秒間隔の断続音が鳴りうる。確度が低いので連続音にはならない
//   (`definite` は includeGpsGuard: false で判定するため 9.00m のまま)。
//   **利用者判断(2026-07-27): 桜川で 8+ 同士が狭所ですれ違う頻度はほぼ無い
//   ため、値は変えず、この検算を記録に残すに留める。**
//   将来この鳴り方が問題になったら、`maxExtrapolationGuardMeters` を
//   艇の大きさに応じて調整するか、8+ の排他領域幅を見直すこと。
// =====================================================

/// accuracy(GPS推定誤差半径)が得られない艇に仮定するGPS誤差 [m]
const assumedGpsAccuracyMeters = 5.0;

/// 静的障害物の swept domain 全幅へ追加するGPS補助帯の係数。
/// ポリゴンの各側へ実際に加える量は、この結果の1/2。
const staticGpsGuardFullWidthFactor = 0.25;

/// 静的障害物の swept domain 全幅へ加える上限 [m](片側は1.5m)。
///
/// 以前は同梱プリセットだけこの帯を0にする特例があり、
/// 「確実(lv3)/不確実(lv2)」の2段判定が静的区域では実質機能していなかった。
/// 特例は撤去し、全区域へ一様に適用する。
const maxStaticGpsGuardFullWidthMeters = 3.0;

/// 2艇の合成GPS accuracyから、中心間距離へ一度だけ追加する係数。
/// 近接した2端末のGPS誤差は同方向へ相関することが多いため1.0より小さい。
const pairGpsCenterDistanceGuardFactor = 0.20;

/// 他艇判定の中心間距離へ加えるGPS補正の上限 [m]。
const maxPairGpsCenterDistanceGuardMeters = 2.5;

// ---------------- 推測航法(外挿)の誤差マージン ----------------
// 受信した他艇は最大 boatPredictionTimeoutSeconds(6秒)まで等速直線で
// 外挿する。5m/sなら30mの推測航法になるのに、以前はその誤差へ
// 追加マージンを一切与えていなかった。相手が漕ぎ始め・漕ぎ止め・
// 向きを変えていれば外挿位置は大きく外れ、そのまま「脅威なし」になる。
//
// 通常運用(近傍時は2秒送信)ではデータ齢は3秒以下に収まるため、
// 実際に効くのは通信が乱れたときだけ。

/// 外挿1秒あたりに加算する位置不確実性 [m/s]。
const extrapolationUncertaintyMetersPerSecond = 0.4;

/// 外挿誤差マージンの上限 [m]。
const maxExtrapolationGuardMeters = 2.5;

// =====================================================
// 航路中心線に沿った予測(蛇行河川対応)
// -----------------------------------------------------
// 桜川は200mおきにカーブが来る区間がある。直線等速で10秒先(最大50m)を
// 予測すると、カーブでは外岸へ突っ込む予測になって誤警告を生み、
// 曲がった先の危険は見落とす。中心線に沿った曲線座標で
// 「川沿いに進む成分」と「岸へ寄る成分」を分けて積分することで、
// 川なりに進む艇へ誤警告を出さず、岸へ向かう艇は正しく検知する。
//
// 中心線が作れない場合は必ず従来の直線予測へ縮退する。
// この機能で警告が止まることは無い。
// =====================================================

/// 航路中心線に沿った予測を有効にする。
const enableChannelAwarePrediction = true;

/// 岸基準線から中心線を推定するときの標本間隔 [m]。
const channelCenterlineSampleIntervalMeters = 25.0;

/// 中心線として妥当と認める川の半幅の範囲 [m]。
/// 桜川の川幅は概ね50m、狭い区間で35m。基準線の向きが揃っていない
/// 区間を捨てるためのガードなので、実測より広めに取る。
const minimumChannelHalfWidthMeters = 8.0;
const maximumChannelHalfWidthMeters = 60.0;

/// 中心線として採用する最小標本数と最小全長 [m]。
const minimumChannelCenterlineSamples = 5;
const minimumChannelCenterlineLengthMeters = 50.0;

/// 予測経路を折れ線で近似するときの最大分割数。
/// 分割するほど円弧に近づくが、掃引回数もこの数に比例する。
const maxChannelPredictionSegments = 6;

/// 1分割あたりの目安距離 [m]。これより短くなる分割は作らない。
const channelPredictionSegmentMinimumLengthMeters = 6.0;

/// 中心線から離れすぎた艇は投影が信頼できないため、直線予測へ戻す [m]。
const maxChannelProjectionOffsetMeters = 80.0;

/// 「川を横断している」と見なす along 速度の下限比率(速度に対する割合)。
///
/// 中心線予測から外すべきなのは**横断**であって**逆行ではない**。
/// 桜川は往復コースであり(DESIGN_PRINCIPLES 1.1)、中心線の向きは岸基準線の
/// 並び順で一意に決まるため、行きか帰りのどちらかは along 速度が必ず負になる。
/// 負を一律に捨てると、航行時間の約半分で直線予測へ縮退し、蛇行区間のたびに
/// カーブの外岸へ膨らんだ予測で誤警告が出る(原則4: 過剰警告は安全機能の破壊)。
/// 逆向きでも川に沿っていることに変わりはなく、曲線座標の積分は
/// 負の along 速度でも中心線を正しく逆に辿る。
///
/// 0.2 は |cos(進行方位 − 接線方位)| の下限。接線から約78.5〜101.5度、
/// つまり「ほぼ真横」の場合だけ直線予測へ戻す。右側通行の片側1レーンを
/// 走る通常の航行は接線±30度以内に収まり(1.2)、この閾値には掛からない。
/// 桟橋への出入りや折り返しの回頭中は一時的にここへ入るが、そのとき
/// along 成分は速度の2割未満で、川に沿って何十メートル進む予測にはならない。
/// 中心線の助けが小さい一方、直線予測は必ず安全側(過剰警告側)へ倒れる。
const minimumChannelAlongSpeedRatio = 0.2;

/// 折れ線近似の残差と、艇が川なりに曲がることを見込んだ横方向マージン [m]。
/// 弦の中央のずれ(サジッタ)から求め、この値で頭打ちにする。
const maxChannelCurvatureMarginMeters = 3.0;

// =====================================================
// すれ違い間隔(DCPA相当)
// -----------------------------------------------------
// 連続掃引は「領域が重なるか」の二値だが、重ならない場合の最接近距離も
// 同時に求まる。これを記録・表示に使うと、すれ違いの余裕を練習後に
// 振り返れる。危険側へ倒れる前の予兆としてlv1(表示のみ)にも使う。
// =====================================================

/// この距離以下ですれ違う見込みなら、領域が重ならなくても注意(lv1)にする [m]。
/// 領域同士の隙間で測るため、艇体間の実距離はこれより広い。
const nearMissSeparationMeters = 2.0;

// =====================================================
// 低速時の方位不確かさ
// -----------------------------------------------------
// 低速時のcourse-over-groundは不安定なため、実装は最後の進行方位を保持する。
// 停止して回頭する場面(折り返し・整列)では、その方位が実際の艇の向きと
// 最大90度ずれ、細長い船体領域が「痩せた」向きで判定されて警告が漏れる。
//
// 船体領域の六角形は中心について点対称なので、方位が180度ずれても形は同じ。
// バック(逆漕ぎ)でCOGが艇首と逆向きになっても領域は正しく、特別扱いは不要。
// 対処が要るのは90度前後の誤差だけ。
// =====================================================

/// この速度以上なら進行方位を信頼する [m/s]。
const shipDomainReliableHeadingSpeedMetersPerSecond = 0.5;

/// 低速時に想定する方位誤差 [度]。艇長の半分 × sin(この角度) を横へ加える。
const shipDomainLowSpeedHeadingUncertaintyDegrees = 35.0;

/// 低速時の横方向拡張の上限 [m]。
/// 川幅35〜50mの桜川で、岸際の休憩中に過剰警告にならない範囲に抑える。
const shipDomainMaxLowSpeedLateralInflationMeters = 4.0;

/// 静的掃引で岸にだけ適用する低速時の横方向拡張係数。
///
/// 停止中の岸は動かないため、方位が不確かでも艇の実体が届く範囲だけで
/// 判定する。風や流れで寄る危険は近接注意(3m)が継続して受け持つ。
/// broad-phase と他艇の低速時拡張はこの値を使わず、従来どおり保守側に残す。
const shoreStaticSweepLowSpeedLateralInflationFactor = 0.0;

/// 岸以外の静的危険区域に使う従来どおりの低速時横拡張係数。
const defaultStaticSweepLowSpeedLateralInflationFactor = 1.0;

// =====================================================
// 逆走注意の方向つき判定
// -----------------------------------------------------
// 逆走注意区域(reverse)は「区域内に現在地があるか」だけで判定していたため、
// 1.2 の右側通行を守って正しく漕いでいても、区域を出入りするたびに鳴っていた
// (実機ログで77分に16回)。原則4に反するので、航路中心線と右側通行から
// 「その位置で進むべき向き」を求め、そこから大きくずれたときだけ発報する。
//
// 中心線が無い・投影が信頼できない場合は、従来どおり「区域内で発報」へ
// 縮退する(原則1)。黙って無効化はしない。
// =====================================================

/// 逆走と判定する、規定進行方位からのずれ [度]。
/// 川を横切る(90度)だけでは逆走にしない。1.2 右側通行・片側1レーン。
const reverseGuidanceHeadingErrorDegrees = 120.0;

/// 中心線からこの距離以内は、左右どちらのレーンにいるか言い切れないため
/// 逆走と判定しない [m]。
///
/// 規定進行方位は「中心線のどちら側にいるか」から決まるので、cross の符号が
/// GPS誤差で反転すると、正しく漕いでいる艇の規定方位が180度ひっくり返り、
/// そのまま逆走の誤判定になる。水上のGPS誤差は5m級が普通
/// ([assumedGpsAccuracyMeters])なので、その幅を判定から外す。
/// 1.2 の片側レーン幅は狭所12.5m・通常15〜20mで、レーン中央を守る艇は
/// 中心線から6m以上離れるため、判定対象からは外れない。
const reverseGuidanceLaneAmbiguityMeters = 5.0;

/// 逆走を発報として確定させるまでの継続時間 [秒]。
///
/// 折り返しの回頭直後・対向艇を避けての斜行・岸への寄せは、いずれも
/// 正常な運用でありながら一瞬だけ逆走の条件を満たす。6秒 @ 5m/s = 30m
/// 進む間の猶予にあたる。カーブ間隔は最短200mなので、気づくのが30m
/// 遅れても次のカーブまでの余裕は失われない。解除は非対称で即座に行う。
const reverseGuidanceConfirmSeconds = 6.0;
