/// system fault(能力欠如の通知)の発報タイミングに関する設定値。
///
/// system fault は「機能を止めない」ための縮退運転の告知であり
/// (DESIGN_PRINCIPLES 原則1)、物理的な衝突警告とは別系統である。
/// 一方で、瞬間的な劣化でフラップさせると原則4「過剰警告は安全機能の
/// 破壊である」に直行する。実機ログ(2026-07-26)では
/// `other_boat_receive_unavailable` が77分で315エピソード発生し、
/// セッション全体の音173回のうち94回を占めた。
/// ここの値はその抑制のためにある。
library;

/// 他艇受信の劣化を system fault として確定するまでの継続時間 [秒]。
///
/// 停止中の送信間隔は10秒(DESIGN_PRINCIPLES 3.4)。通信ジッタと
/// 1スナップショットぶんの取りこぼしでは発報させない。
/// 10秒周期の送信が1回丸ごと欠けても、次の周期が来るまでは待つ。
const dynamicReceiveFaultConfirmSec = 15;

/// 復旧を確定するまでの継続時間 [秒]。確定と解除の両方に履歴を要求して
/// フラップを止める。片側だけのヒステリシスでは、確定した fault が
/// 一瞬の受信成功で消えて即座に戻る往復が残る。
const dynamicReceiveFaultClearSec = 15;

/// GPSは届いているのに衝突評価が完了していない状態を記録する閾値 [秒]。
///
/// 1秒タイマーが動いていることと、評価が完了していることは別である。
/// これは [GpsHealthMonitor] が扱うGPS入力途絶とは区別し、評価停止だけを
/// 診断する。表示は直ちに縮退運転へ切り替え、音声は鳴らさない。
const safetyEvaluationStallSeconds = 3;
