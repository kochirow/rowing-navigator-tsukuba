/// 陸上判定(`AshoreDetector`)の設定値。
///
/// ここで決めるのは「**警告音を止めてよいほど確実に陸上か**」だけである。
/// 検知・画面表示・記録・位置共有を止める判断には使わない
/// (DESIGN_PRINCIPLES 原則1「機能を止めない」)。
///
/// 全ての値は「水上で誤って成立しないこと」を最優先に決めてある。
/// 逆方向(陸上なのに成立しない)の誤りは、音が今までどおり鳴るだけで
/// 安全機能は失われないため、こちら側へ倒す。
library;

/// 岸の基準線より陸側へこれ以上入っていれば「陸上」の候補とする [m]。
///
/// DESIGN_PRINCIPLES 1.1「川幅40〜50m・狭所35m」、
/// 1.4「岸から数mを走るのは正常」。
/// 水上を漕いでいる艇は常に基準線の**水面側**にいる。水上でこの条件が
/// 成立するには、岸に最も寄った状態からさらに 20m 級のGPS誤差が
/// 陸方向へ乗る必要がある。
const ashoreLandSideMarginMeters = 12.0;

/// GPS推定誤差(accuracy)に掛けて、上のマージンへ上乗せする係数。
///
/// 実効マージン = max([ashoreLandSideMarginMeters], accuracy × この係数)。
/// 誤差が大きいときほど陸上と決めつけない。
const ashoreAccuracyMarginFactor = 2.0;

/// 陸上と確定するまでに条件が継続すべき時間。
///
/// 単発の異常測位では確定させない。実機ログでは艇を運んでいる区間が
/// 600秒続いていたため、30秒の待ちは実用上の損失にならない。
const ashoreConfirmationDuration = Duration(seconds: 30);

/// 岸の基準線がこの距離より遠い場合、陸側/水面側を判定しない [m]。
///
/// 霞ヶ浦の沖のように基準線から大きく離れた場所では、基準線の
/// 半平面を延長した判定は信頼できない。判定不能は**水上扱い**にして
/// 警告を止めない(原則6「データ欠損は安全の根拠にならない」)。
const ashoreBaselineRelevanceRadiusMeters = 200.0;
