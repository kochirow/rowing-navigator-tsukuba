/// アプリがいま「どの時間」にいるか。
///
/// このアプリの操作は、機能の種類ではなく**時間と姿勢**で分かれる。
///
/// - [ashore] 出艇前 … 陸上・両手が空く・時間がある。準備と管理をする
/// - [navigating] 航行中 … 艇上・両手が塞がる・チラ見しかできない
/// - [watching] 監視中 … 陸上・端末を操作できる。艇の状況を見て、直す
///
/// `NavMode` は「自艇を出しているか / 他艇を見ているか」という
/// 安全経路の区分で、こちらは「利用者がいまどんな姿勢にいるか」という
/// 提示上の区分である。`NavMode.observer` は出艇前と監視中の両方を含むため、
/// 画面の出し分けにはそのまま使えない。
enum HomePhase {
  ashore,
  navigating,
  watching;

  /// 出艇前だけタブを出す。航行中・監視中は地図を全画面で使う。
  bool get showsTabs => this == HomePhase.ashore;
}
